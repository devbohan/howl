/**
 * Bundles the bookmarklet from the same capture code the app tests, so the two
 * can never drift. Emits a `javascript:` URL you drag to the bookmarks bar.
 */
import { build } from 'esbuild'
import { writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const adminUrl = process.env.ADMIN_URL ?? 'http://localhost:5173/admin.html'

const result = await build({
  entryPoints: [resolve('src/admin/bookmarklet/entry.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  write: false,
  define: { __ADMIN_URL__: JSON.stringify(adminUrl) },
})

const code = result.outputFiles[0].text.trim().replace(/;$/, '')
const href = 'javascript:' + encodeURIComponent(`(function(){${code}})()`)

await writeFile(
  resolve('src/admin/bookmarklet/generated.ts'),
  `// Generated by scripts/build-bookmarklet.mjs — do not edit.\n` +
    `// Rebuild with: ADMIN_URL=<your admin url> npm run build:bookmarklet\n` +
    `export const BOOKMARKLET_HREF = ${JSON.stringify(href)}\n` +
    `export const BOOKMARKLET_TARGET = ${JSON.stringify(adminUrl)}\n`,
)

console.log(`书签脚本已生成（${(href.length / 1024).toFixed(1)}KB），指向 ${adminUrl}`)
