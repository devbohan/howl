export const LocaleContext = createContext<Locale>('en')

export function useT() {
  const locale = useContext(LocaleContext)
  const t = (key: Key) => DICT[locale][key]
  /** Resolve a localized field from mock data, falling back to English. */
  const tl = (value: L | undefined) => (value ? value[locale] ?? value.en : '')
  return { t, tl, locale }
}
